-- 1. Create product_batches table if it doesn't exist
CREATE TABLE IF NOT EXISTS product_batches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT REFERENCES products(id) ON DELETE CASCADE,
  bchcode INTEGER NOT NULL,
  batch TEXT,
  mrp NUMERIC NOT NULL,
  stock INTEGER NOT NULL DEFAULT 0,
  UNIQUE(product_id, bchcode)
);

-- 2. Configure Row Level Security (RLS)
ALTER TABLE product_batches ENABLE ROW LEVEL SECURITY;

-- Allow public read access to batches
DROP POLICY IF EXISTS "Allow public read access" ON product_batches;
CREATE POLICY "Allow public read access" ON product_batches FOR SELECT USING (true);

-- Allow full access for service_role / sync script
DROP POLICY IF EXISTS "Allow service_role write access" ON product_batches;
CREATE POLICY "Allow service_role write access" ON product_batches FOR ALL USING (true);

-- 3. Cleanup existing triggers on the orders table to avoid duplicate stock decrementing
DO $$
DECLARE
    trg RECORD;
BEGIN
    FOR trg IN 
        SELECT trigger_name 
        FROM information_schema.triggers 
        WHERE event_object_table = 'orders' 
          AND trigger_schema = 'public'
    LOOP
        EXECUTE 'DROP TRIGGER IF EXISTS ' || trg.trigger_name || ' ON orders;';
    END LOOP;
END $$;

-- 4. Create trigger function to handle order stock change with batch support
CREATE OR REPLACE FUNCTION handle_order_stock_change()
RETURNS TRIGGER AS $$
DECLARE
  item jsonb;
  prod_id bigint;
  item_qty integer;
  item_bchcode integer;
BEGIN
  -- Revert stock for OLD items (on DELETE or UPDATE)
  IF (TG_OP = 'DELETE' OR TG_OP = 'UPDATE') THEN
    FOR item IN SELECT * FROM jsonb_array_elements(OLD.items) LOOP
      prod_id := (item->>'id')::bigint;
      item_qty := (item->>'qty')::integer;
      item_bchcode := COALESCE((item->>'bchcode')::integer, 0);

      UPDATE product_batches
      SET stock = stock + item_qty
      WHERE product_id = prod_id AND bchcode = item_bchcode;

      IF NOT FOUND THEN
        INSERT INTO product_batches (product_id, bchcode, batch, mrp, stock)
        VALUES (prod_id, item_bchcode, '', COALESCE((item->>'mrp')::numeric, 0), item_qty)
        ON CONFLICT (product_id, bchcode) DO UPDATE
        SET stock = product_batches.stock + item_qty;
      END IF;

      -- Update main products stock to sum of all batches
      UPDATE products
      SET stock = (SELECT COALESCE(SUM(stock), 0) FROM product_batches WHERE product_id = prod_id)
      WHERE id = prod_id;
    END LOOP;
  END IF;

  -- Deduct stock for NEW items (on INSERT or UPDATE)
  IF (TG_OP = 'INSERT' OR TG_OP = 'UPDATE') THEN
    FOR item IN SELECT * FROM jsonb_array_elements(NEW.items) LOOP
      prod_id := (item->>'id')::bigint;
      item_qty := (item->>'qty')::integer;
      item_bchcode := COALESCE((item->>'bchcode')::integer, 0);

      UPDATE product_batches
      SET stock = stock - item_qty
      WHERE product_id = prod_id AND bchcode = item_bchcode;

      IF NOT FOUND THEN
        INSERT INTO product_batches (product_id, bchcode, batch, mrp, stock)
        VALUES (prod_id, item_bchcode, '', COALESCE((item->>'mrp')::numeric, 0), -item_qty)
        ON CONFLICT (product_id, bchcode) DO UPDATE
        SET stock = product_batches.stock - item_qty;
      END IF;

      -- Update main products stock to sum of all batches
      UPDATE products
      SET stock = (SELECT COALESCE(SUM(stock), 0) FROM product_batches WHERE product_id = prod_id)
      WHERE id = prod_id;
    END LOOP;
  END IF;

  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

-- 5. Recreate trigger
CREATE TRIGGER trg_order_stock_change
AFTER INSERT OR UPDATE OR DELETE ON orders
FOR EACH ROW EXECUTE FUNCTION handle_order_stock_change();
